// Exporter strategy rendering printable landscape PDF timetable documents via PDFKit.
import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import type { ExportFormat } from '@slotly/contracts';
import type {
  IExporter,
  ExportData,
} from '../../interfaces/exporter.interface';

const DAY_NAMES = [
  'Sunday',
  'Monday',
  'Tuesday',
  'Wednesday',
  'Thursday',
  'Friday',
  'Saturday',
];

/** Strategy implementation generating PDF timetable grids. */
@Injectable()
export class PdfExporter implements IExporter {
  readonly format: ExportFormat = 'pdf';
  readonly mimeType = 'application/pdf';
  readonly fileExtension = 'pdf';

  async export(data: ExportData): Promise<Buffer> {
    return new Promise<Buffer>((resolve, reject) => {
      try {
        const doc = new PDFDocument({
          size: 'A4',
          layout: 'landscape',
          margin: 30,
          info: {
            Title: data.title,
            Author: 'Slotly Academic Timetable Platform',
          },
        });

        const buffers: Buffer[] = [];
        doc.on('data', (chunk: Buffer) => buffers.push(chunk));
        doc.on('end', () => resolve(Buffer.concat(buffers)));
        doc.on('error', (err) => reject(err));

        // Header
        doc.fontSize(16).font('Helvetica-Bold').text(data.projectName, 30, 30);
        doc
          .fontSize(11)
          .font('Helvetica')
          .fillColor('#666666')
          .text(
            `${data.entityType.toUpperCase()}: ${data.entityName} | ${data.title}`,
            30,
            50,
          );
        doc.moveDown(1);

        const activeDays =
          typeof data.day === 'number'
            ? [data.day]
            : data.settings.days || [1, 2, 3, 4, 5];
        const periodsCount = data.settings.periodsPerDay || 7;

        // Draw Table
        const startX = 30;
        let startY = 80;
        const totalWidth = 780;
        const dayColWidth = 80;
        const periodColWidth = (totalWidth - dayColWidth) / periodsCount;
        const rowHeight = 45;

        // Header Row (Periods)
        doc.rect(startX, startY, totalWidth, 24).fill('#111111');
        doc.fillColor('#FFFFFF').fontSize(9).font('Helvetica-Bold');
        doc.text('Day / Period', startX + 5, startY + 7, {
          width: dayColWidth - 10,
        });

        for (let p = 1; p <= periodsCount; p++) {
          const colX = startX + dayColWidth + (p - 1) * periodColWidth;
          doc.text(`P${p}`, colX + 4, startY + 7, {
            width: periodColWidth - 8,
            align: 'center',
          });
        }

        startY += 24;

        // Rows for each active day
        for (const d of activeDays) {
          const dayName = DAY_NAMES[d] || `Day ${d}`;

          // Day label background
          doc.rect(startX, startY, dayColWidth, rowHeight).fill('#F3F4F6');
          doc.fillColor('#111111').font('Helvetica-Bold').fontSize(9);
          doc.text(dayName, startX + 5, startY + 16, {
            width: dayColWidth - 10,
          });

          // Periods columns
          for (let p = 1; p <= periodsCount; p++) {
            const colX = startX + dayColWidth + (p - 1) * periodColWidth;
            doc.rect(colX, startY, periodColWidth, rowHeight).stroke('#E5E7EB');

            const entry = data.entries.find(
              (e) => e.day === d && e.startPeriod === p,
            );

            if (entry) {
              doc
                .rect(colX + 1, startY + 1, periodColWidth - 2, rowHeight - 2)
                .fill('#FAFAFA');
              doc.fillColor('#111111').font('Helvetica-Bold').fontSize(8);
              const label = entry.subjectId || entry.type;
              doc.text(label, colX + 3, startY + 6, {
                width: periodColWidth - 6,
                align: 'center',
              });

              doc.fillColor('#666666').font('Helvetica').fontSize(7);
              const subText = [entry.facultyId, entry.roomId]
                .filter(Boolean)
                .join(' • ');
              if (subText) {
                doc.text(subText, colX + 3, startY + 22, {
                  width: periodColWidth - 6,
                  align: 'center',
                });
              }
            }
          }

          startY += rowHeight;
        }

        // Footer
        doc
          .fillColor('#999999')
          .fontSize(8)
          .font('Helvetica')
          .text(
            `Generated by Slotly on ${new Date().toLocaleDateString()}`,
            30,
            550,
            { align: 'right', width: totalWidth },
          );

        doc.end();
      } catch (err) {
        reject(err);
      }
    });
  }
}
